"""Re-captures the terminal transcripts shown on the website from real runs.

Only deterministic commands are captured (CHECK-STANDARDS, OKF-VIEW, CONFIG, HELP),
so the website never shows invented output for them. Run from the repository root:

    python scripts/capture_website_transcripts.py [--at COMMIT] [--okf-samples PATH/TO/open-knowledge-format/bundles]

--at COMMIT measures a clean temporary clone of that commit (the standards config is
copied in and git-ignored there), so the transcripts are not marked "(dirty)".

Writes website/assets/js/transcripts.js.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "website" / "assets" / "js" / "transcripts.js"
CONFIG = "website/demo/archai_self_standards.yaml"


def run(args, cwd, code_root):
    # PYTHONPATH makes the CLI import the ArchAI code of the analyzed checkout.
    env = dict(os.environ, ARCHAI_DEV_MODE="1", NO_COLOR="1", PYTHONIOENCODING="utf-8", PYTHONPATH=str(code_root))
    env.pop("FORCE_COLOR", None)
    proc = subprocess.run([sys.executable, "-m", "ai_architect.cli", *args], cwd=cwd, env=env,
                          capture_output=True, text=True, encoding="utf-8")
    stderr = [l for l in proc.stderr.splitlines() if "[INFO]" not in l and "[WARNING]" not in l]
    return {"command": "ai-architect " + " ".join(args), "exit": proc.returncode,
            "stderr": stderr, "stdout": proc.stdout.rstrip("\n").splitlines()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--at", help="Commit to measure in a clean temporary clone (default: working tree)")
    parser.add_argument("--okf-samples", help="Path to the bundles/ folder of GoogleCloudPlatform/open-knowledge-format")
    opts = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        target = ROOT
        if opts.at:
            target = Path(tmp) / ROOT.name  # ArchAI reports the folder name as the repository
            subprocess.run(["git", "clone", "--quiet", "--no-checkout", str(ROOT), str(target)], check=True)
            subprocess.run(["git", "checkout", "--quiet", opts.at], cwd=target, check=True)
            (target / CONFIG).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(ROOT / CONFIG, target / CONFIG)
            with open(target / ".git" / "info" / "exclude", "a", encoding="utf-8") as f:
                f.write("\n/" + CONFIG + "\n")
        t, commit = capture(target, opts)
    write(t, commit, opts)


def capture(target, opts):
    commit = subprocess.run(["git", "rev-parse", "--short=12", "HEAD"], cwd=target,
                            capture_output=True, text=True).stdout.strip()
    r = lambda args, cwd=target: run(args, cwd, target)
    bundle = target / "bundle"  # ignored by .gitignore; removed afterwards
    shutil.rmtree(bundle, ignore_errors=True)
    t = {}
    try:
        t["check"] = r(["CHECK-STANDARDS", ".", "--config", CONFIG, "--okf-out", "bundle", "--preview"])
        t["findings"] = r(["OKF-VIEW", "bundle", "findings", "--status", "violation", "--no-color"])
        fan_out = next(p.stem for p in (bundle / "findings").glob("F-*.md")
                       if "coupling_threshold" in p.read_text(encoding="utf-8"))
        t["finding"] = r(["OKF-VIEW", "bundle", fan_out, "--no-color"])
        t["module"] = r(["OKF-VIEW", "bundle", "ai_architect.standards.rules", "--no-color"])
        t["config"] = r(["CONFIG"])
        t["help"] = r(["HELP"])
        t["defaults"] = r(["CHECK-STANDARDS", ".", "--okf-out", "bundle", "--preview"])
        # Ledger (TRACE) reads archai_report.json from a previous AUDIT run; in a clean
        # folder its real output is the "run AUDIT first" message.
        with tempfile.TemporaryDirectory() as empty:
            t["trace"] = r(["TRACE", "T001"], cwd=empty)
    finally:
        shutil.rmtree(bundle, ignore_errors=True)
    if opts.okf_samples:
        samples = Path(opts.okf_samples)
        t["acme"] = r(["OKF-VIEW", "acme_retail", "--no-color"], cwd=samples)
        t["acme_concept"] = r(["OKF-VIEW", "acme_retail", "gross-margin-period", "--no-color"], cwd=samples)
    return t, commit


def write(t, commit, opts):
    meta = {"commit": commit, "captured_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "config": CONFIG, "clean_checkout": bool(opts.at)}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/capture_website_transcripts.py from real ArchAI runs. Do not edit by hand.\n"
        f"window.ARCHAI_TRANSCRIPTS_META = {json.dumps(meta)};\n"
        f"window.ARCHAI_TRANSCRIPTS = {json.dumps(t, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(t)} transcripts, commit {commit})")


if __name__ == "__main__":
    main()
