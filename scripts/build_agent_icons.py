AGENT_FAMILY = {"plumb": "proof", "atlas": "proof", "ledger": "proof", "surveyor": "insight",
                "seismograph": "insight", "draftsman": "insight", "interpreter": "insight",
                "foreman": "workflow", "almanac": "labs"}
FAMILY_NAMES = {"proof": "PROOF", "insight": "INSIGHT", "workflow": "WORKFLOW", "labs": "LABS"}


def rows(bitmap):
    lines = [l for l in bitmap.strip("\n").splitlines()]
    assert len(lines) == 16 and all(len(l) == 16 for l in lines), [len(l) for l in lines]
    return lines


def pixels(bitmap, ox=0, oy=0, scale=1, fill=INK):
    out = []
    for y, line in enumerate(rows(bitmap)):
        x = 0
        while x < 16:
            if line[x] == "#":
                start = x
                while x < 16 and line[x] == "#":
                    x += 1
                out.append(f'<rect x="{ox + start * scale}" y="{oy + y * scale}" width="{(x - start) * scale}" '
                           f'height="{scale}" fill="{fill}"/>')
            else:
                x += 1
    return "".join(out)


def agent_icon(name):
    """24x24 tile: 16x16 glyph centred in a frame. Insight agents get a dashed frame."""
    family = AGENT_FAMILY[name]
    dashed = ' stroke-dasharray="2 2"' if family == "insight" else ""
    bg = ORANGE if family == "proof" else PAPER
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="48" height="48" '
            f'shape-rendering="crispEdges" role="img" aria-label="{name.title()} icon">'
            f'<rect x="1" y="1" width="22" height="22" fill="{bg}" stroke="{INK}" stroke-width="2"{dashed}/>'
            f'{pixels(GLYPHS[name], 4, 4)}</svg>')


def family_badge(family):
    """Window-tab style badge: glyph block plus family name."""
    label = FAMILY_NAMES[family]
    width = 34 + len(label) * 9
    dashed = ' stroke-dasharray="3 2"' if family == "insight" else ""
    block = ORANGE if family == "proof" else SOFT if family == "labs" else PAPER
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} 24" width="{width * 2}" height="48" '
            f'shape-rendering="crispEdges" role="img" aria-label="{label.title()} family">'
            f'<rect x="1" y="1" width="{width - 2}" height="22" fill="{INK}" stroke="{INK}" stroke-width="2"{dashed}/>'
            f'<rect x="1" y="1" width="22" height="22" fill="{block}" stroke="{INK}" stroke-width="2"{dashed}/>'
            f'{pixels(FAMILY_GLYPHS[family], 4, 4)}'
            f'<text x="29" y="16.5" fill="{ORANGE if family == "proof" else PAPER}" font-family="Silkscreen, monospace" '
            f'font-size="10" letter-spacing="1">{label}</text></svg>')


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in GLYPHS:
        (OUT / f"{name}.svg").write_text(agent_icon(name), encoding="utf-8")
    for family in FAMILY_GLYPHS:
        (OUT / f"family-{family}.svg").write_text(family_badge(family), encoding="utf-8")
    tiles = "".join(f'<figure><img src="{n}.svg" width="96" height="96"><figcaption>{n}</figcaption></figure>'
                    for n in GLYPHS)
    badges = "".join(f'<img src="family-{f}.svg" height="48">' for f in FAMILY_GLYPHS)
    (OUT / "sheet.html").write_text(
        '<!doctype html><meta charset="utf-8"><title>ArchAI agent icons</title>'
        '<link href="https://fonts.googleapis.com/css2?family=Silkscreen&family=JetBrains+Mono&display=swap" rel="stylesheet">'
        '<style>body{font-family:"JetBrains Mono",monospace;margin:32px;background:#fff;color:#141414}'
        '.row{display:flex;gap:24px;flex-wrap:wrap;margin:24px 0}figure{margin:0;text-align:center;font-size:12px}'
        'img{image-rendering:pixelated}</style>'
        f'<h1>ArchAI agent icons</h1><div class="row">{tiles}</div><h2>Family badges</h2><div class="row">{badges}</div>',
        encoding="utf-8")
    print(f"wrote {len(GLYPHS)} agent icons and {len(FAMILY_GLYPHS)} family badges to {OUT}")


if __name__ == "__main__":
    main()
