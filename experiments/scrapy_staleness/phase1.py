def svg_lines(title, xlabels, series, ylabel, ymax=None, width=720, height=360):
    """Minimal stdlib line chart (no plotting library)."""
    pad_l, pad_r, pad_t, pad_b = 60, 150, 36, 48
    w, h = width - pad_l - pad_r, height - pad_t - pad_b
    values = [v for pts in series.values() for v in pts if v is not None]
    top = ymax if ymax is not None else (max(values) * 1.1 if values else 1)
    x = lambda i: pad_l + (w * i / max(len(xlabels) - 1, 1))
    y = lambda v: pad_t + h - (h * v / top if top else 0)
    colors = ["#E8590C", "#141414", "#2f7d32", "#6a4fd6", "#9a6700"]
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" font-family="monospace" font-size="11">',
           f'<rect width="{width}" height="{height}" fill="#fff"/>',
           f'<text x="{pad_l}" y="20" font-size="13" font-weight="bold">{title}</text>']
    for k in range(5):
        v = top * k / 4
        out.append(f'<line x1="{pad_l}" x2="{pad_l + w}" y1="{y(v):.1f}" y2="{y(v):.1f}" stroke="#ddd"/>')
        out.append(f'<text x="{pad_l - 6}" y="{y(v) + 4:.1f}" text-anchor="end">{v:.2f}</text>' if top <= 1.5
                   else f'<text x="{pad_l - 6}" y="{y(v) + 4:.1f}" text-anchor="end">{v:.0f}</text>')
    for i, lab in enumerate(xlabels):
        out.append(f'<text x="{x(i):.1f}" y="{pad_t + h + 18}" text-anchor="middle">{lab}</text>')
    out.append(f'<text x="14" y="{pad_t + h / 2}" transform="rotate(-90 14 {pad_t + h / 2})" text-anchor="middle">{ylabel}</text>')
    for n, (name, pts) in enumerate(series.items()):
        c = colors[n % len(colors)]
        coords = [(x(i), y(v)) for i, v in enumerate(pts) if v is not None]
        out.append(f'<polyline fill="none" stroke="{c}" stroke-width="2" points="{" ".join(f"{a:.1f},{b:.1f}" for a, b in coords)}"/>')
        out += [f'<circle cx="{a:.1f}" cy="{b:.1f}" r="3" fill="{c}"/>' for a, b in coords]
        out.append(f'<rect x="{pad_l + w + 14}" y="{pad_t + n * 18}" width="10" height="10" fill="{c}"/>'
                   f'<text x="{pad_l + w + 30}" y="{pad_t + n * 18 + 9}">{name}</text>')
    out.append("</svg>")
    return "\n".join(out)


def classify_rewrites(target):
    """For unchanged edges labelled 'import statement no longer present': how the statement changed."""
    new = json.loads((GRAPHS / f"{target}.json").read_text(encoding="utf-8"))["graph"]
    now = {}
    for e in new["edges"]:
        if e["scope"] == "module":
            now.setdefault((e["source"], e["target"]), []).append(ast.parse(e["statement"]).body[0])
    key = lambda n: (type(n).__name__, getattr(n, "module", None), getattr(n, "level", 0))
    counts = {"same 'from' module, names added": 0, "same 'from' module, names removed": 0,
              "same 'from' module, names replaced": 0, "rewritten in another form": 0}
    with open(RESULTS / "verdicts" / f"{BASE}_to_{target}.jsonl", encoding="utf-8") as f:
        for line in f:
            v = json.loads(line)
            pair = (v.get("source"), v.get("target"))
            if v["kind"] != "edge" or v["label"] != STALE or pair not in now or                     v["reason"] != "import statement no longer present":
                continue
            old = ast.parse(v["statement"]).body[0]
            same = [n for n in now[pair] if key(n) == key(old)]
            if not same:
                counts["rewritten in another form"] += 1
                continue
            o = {a.name for a in old.names}
            if any({a.name for a in n.names} > o for n in same):
                counts["same 'from' module, names added"] += 1
            elif any({a.name for a in n.names} < o for n in same):
                counts["same 'from' module, names removed"] += 1
            else:
                counts["same 'from' module, names replaced"] += 1
    return counts


def pct(v):
    return "n/a" if v is None else f"{100 * v:.1f}%"


