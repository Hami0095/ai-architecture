def git(*args):
    return subprocess.run(["git", "-C", str(REPOS / "scrapy"), *args], capture_output=True, text=True,
                          check=True).stdout


# --- 0. Checkouts ------------------------------------------------------------------

def ensure_checkouts():
    clone = REPOS / "scrapy"
    if not clone.exists():
        REPOS.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", CONFIG["subject"]["url"], str(clone)], check=True)
    for tag, commit in CONFIG["subject"]["tags"].items():
        actual = git("rev-parse", f"{tag}^{{commit}}").strip()
        if actual != commit:
            raise SystemExit(f"Tag {tag} points to {actual}, expected {commit}")
        target = REPOS / tag
        if not (target / "scrapy" / "__init__.py").exists():
            target.mkdir(parents=True, exist_ok=True)
            archive = subprocess.run(["git", "-C", str(clone), "archive", "--format=tar", tag, "scrapy"],
                                     capture_output=True, check=True).stdout
            subprocess.run(["tar", "-x", "-C", str(target)], input=archive, check=True)


# --- 1. Graphs ------------------------------------------------------------------------

def load_graph(tag) -> RepoGraph:
    return RepoGraph.from_dict(json.loads((GRAPHS / f"{tag}.json").read_text(encoding="utf-8"))["graph"])


def build_graphs():
    GRAPHS.mkdir(exist_ok=True)
    for tag in TAGS:
        out = GRAPHS / f"{tag}.json"
        if out.exists():
            continue
        started = time.perf_counter()
        graph = build_repo_graph(REPOS / tag)
        seconds = time.perf_counter() - started
        module_pairs = {(e.source, e.target) for e in graph.edges if e.scope == "module"}
        meta = {"tag": tag, "commit": CONFIG["subject"]["tags"][tag], "build_seconds": round(seconds, 4),
                "modules": len(graph.modules), "edge_records": len(graph.edges),
                "module_scope_pairs": len(module_pairs), "parse_failures": sorted(
                    m for m, f in graph.modules.items() if f.parse_error),
                "archai_version": ARCHAI_VERSION, "engine_sha256": engine_hash(),
                "python": platform.python_version()}
        out.write_text(json.dumps({"meta": meta, "graph": graph.to_dict()}, indent=1, sort_keys=True),
                       encoding="utf-8", newline="\n")
        # OKF bundle of the same graph (ArchAI default config: only the cycle rule is evaluated)
        report = run_check(None, graph=graph, config=parse_config({}), fact_source="source-extraction")
        export_bundle(report, str(BUNDLES / tag))
        print(f"graph {tag}: {meta['modules']} modules, {meta['module_scope_pairs']} pairs, {seconds:.2f}s")


# --- 2. Drift matrix -------------------------------------------------------------------

def module_pairs(g: RepoGraph):
    return {(e.source, e.target) for e in g.edges if e.scope == "module"}


def renames(old_tag, new_tag):
    """Module moves git detects between two tags (rename detection, default threshold)."""
    out = git("diff", "--find-renames", "--name-status", old_tag, new_tag, "--", "scrapy/")
    moved = []
    for line in out.splitlines():
        parts = line.split("\t")
        if parts[0].startswith("R") and parts[1].endswith(".py") and parts[2].endswith(".py"):
            moved.append({"old": _canonical_name(parts[1], [])[0], "new": _canonical_name(parts[2], [])[0],
                          "similarity": int(parts[0][1:])})
    return moved


def drift_matrix(graphs):
    out = {}
    for i, a in enumerate(TAGS):
        for b in TAGS[i:]:
            ga, gb = graphs[a], graphs[b]
            ma, mb = set(ga.modules), set(gb.modules)
            pa, pb = module_pairs(ga), module_pairs(gb)
            added, removed = mb - ma, ma - mb
            moved = [m for m in renames(a, b) if m["old"] in removed and m["new"] in added] if a != b else []
            out[f"{a}->{b}"] = {
                "built_at": a, "checked_at": b,
                "modules_added": sorted(added - {m["new"] for m in moved}),
                "modules_removed": sorted(removed - {m["old"] for m in moved}),
                "modules_moved": moved,
                "edges_added": len(pb - pa), "edges_removed": len(pa - pb),
                "edges_kept": len(pa & pb), "modules_kept": len(ma & mb),
            }
    return out


# --- 3/4. Verifier evaluation ----------------------------------------------------------

def evaluate(old: RepoGraph, new: RepoGraph, new_root: Path, window):
    """Scores verifier labels against ground truth for module facts and module-scope edge facts."""
    result = verify_graph(old, new_root, window=window, edge_scopes=["module"])
    new_modules, new_pairs = set(new.modules), module_pairs(new)
    scores = {}
    for kind in ("module", "edge"):
        tally = {"truly_stale": 0, "truly_unchanged": 0, "labels": {VERIFIED: 0, STALE: 0, UNVERIFIABLE: 0},
                 "stale_tp": 0, "stale_fp": 0, "false_verified": 0, "unchanged_verified": 0,
                 "unverifiable_on_stale": 0, "fp_reasons": {}}
        for v in result.verdicts:
            if v.kind != kind:
                continue
            truly_stale = (v.fact["module"] not in new_modules) if kind == "module" else \
                ((v.fact["source"], v.fact["target"]) not in new_pairs)
            tally["truly_stale" if truly_stale else "truly_unchanged"] += 1
            tally["labels"][v.label] += 1
            if v.label == STALE:
                if truly_stale:
                    tally["stale_tp"] += 1
                else:
                    tally["stale_fp"] += 1
                    key = re.sub(r" of line \d+.*", "", v.reason)  # group by kind of change
                    tally["fp_reasons"][key] = tally["fp_reasons"].get(key, 0) + 1
            elif v.label == VERIFIED:
                tally["false_verified" if truly_stale else "unchanged_verified"] += 1
            elif truly_stale:
                tally["unverifiable_on_stale"] += 1
        labelled_stale = tally["stale_tp"] + tally["stale_fp"]
        tally["stale_precision"] = round(tally["stale_tp"] / labelled_stale, 4) if labelled_stale else None
        tally["stale_recall"] = round(tally["stale_tp"] / tally["truly_stale"], 4) if tally["truly_stale"] else None
        tally["unchanged_verified_share"] = (round(tally["unchanged_verified"] / tally["truly_unchanged"], 4)
                                             if tally["truly_unchanged"] else None)
        scores[kind] = tally
    return scores, result


def missing_knowledge(old: RepoGraph, new: RepoGraph):
    return {"new_modules": len(set(new.modules) - set(old.modules)),
            "new_edges": len(module_pairs(new) - module_pairs(old)),
            "new_edges_share_of_current": round(len(module_pairs(new) - module_pairs(old)) / len(module_pairs(new)), 4)}


def distance(a, b):
    commits = int(git("rev-list", "--count", f"{a}..{b}").strip())
    da = datetime.fromisoformat(git("log", "-1", "--format=%cI", f"{a}^{{commit}}").strip())
    db = datetime.fromisoformat(git("log", "-1", "--format=%cI", f"{b}^{{commit}}").strip())
    return {"releases": TAGS.index(b) - TAGS.index(a), "commits": commits, "days": (db - da).days}


def timings(old: RepoGraph, new_root: Path, repeats):
    verify, rebuild = [], []
    for _ in range(repeats):
        t = time.perf_counter(); verify_graph(old, new_root, edge_scopes=["module"]); verify.append(time.perf_counter() - t)
        t = time.perf_counter(); build_repo_graph(new_root); rebuild.append(time.perf_counter() - t)
    return {"verify_seconds_median": round(statistics.median(verify), 4),
            "rebuild_seconds_median": round(statistics.median(rebuild), 4),
            "verify_seconds": [round(x, 4) for x in verify], "rebuild_seconds": [round(x, 4) for x in rebuild]}


def run_all():
    started = datetime.now(timezone.utc)
    ensure_checkouts()
    build_graphs()
    graphs = {t: load_graph(t) for t in TAGS}
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "verdicts").mkdir(exist_ok=True)

    drift = drift_matrix(graphs)
    (RESULTS / "drift_matrix.json").write_text(json.dumps(drift, indent=1), encoding="utf-8", newline="\n")

    evaluation = {}
    for a, b in combinations(TAGS, 2):
        scores, result = evaluate(graphs[a], graphs[b], REPOS / b, DEFAULT_WINDOW)
        row = {"built_at": a, "checked_at": b, "distance": distance(a, b), "window": DEFAULT_WINDOW,
               **scores, "missing_knowledge": missing_knowledge(graphs[a], graphs[b]),
               "verify_seconds": result.seconds, "files_read": result.files_read}
        evaluation[f"{a}->{b}"] = row
        if a == BASE:
            with open(RESULTS / "verdicts" / f"{a}_to_{b}.jsonl", "w", encoding="utf-8", newline="\n") as f:
                for v in result.verdicts:
                    f.write(json.dumps({"kind": v.kind, "label": v.label, "reason": v.reason,
                                        "found_line": v.found_line, **v.fact}, sort_keys=True) + "\n")
    (RESULTS / "verifier_evaluation.json").write_text(json.dumps(evaluation, indent=1), encoding="utf-8", newline="\n")

    sensitivity = {}
    for b in TAGS[1:]:
        sensitivity[b] = {str(w if w is not None else "whole-file"): evaluate(graphs[BASE], graphs[b], REPOS / b, w)[0]
                          for w in WINDOWS}
    (RESULTS / "window_sensitivity.json").write_text(json.dumps(sensitivity, indent=1), encoding="utf-8", newline="\n")

    repeats = CONFIG["verifier"]["timing_repeats"]
    timing = {b: timings(graphs[BASE], REPOS / b, repeats) for b in TAGS[1:]}
    (RESULTS / "timings.json").write_text(json.dumps(timing, indent=1), encoding="utf-8", newline="\n")

    meta = {"phase": 1, "started_at": started.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "finished_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "archai_version": ARCHAI_VERSION, "engine_sha256": engine_hash(),
            "archai_commit": subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True,
                                            text=True).stdout.strip(),
            "archai_dirty": bool(subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--", "ai_architect"],
                                                capture_output=True, text=True).stdout.strip()),
            "python": platform.python_version(), "platform": platform.platform(),
            "tags": CONFIG["subject"]["tags"], "window": DEFAULT_WINDOW, "llm_used": False}
    (RESULTS / "run_meta.json").write_text(json.dumps(meta, indent=1), encoding="utf-8", newline="\n")
    write_report()


